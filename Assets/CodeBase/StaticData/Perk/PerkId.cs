        /// <summary>Меч: ширший замах. Значення = додаткові градуси до кута атаки (максимум 360 разом).</summary>
        WideSwing = 2,

        /// <summary>Меч: лікування за замах, що влучив хоча б в одного ворога. Значення = HP за замах.</summary>
        Vampirism = 3,

