namespace CodeBase.StaticData.Perk
{
    /// <summary>
    /// Перки — апгрейди, що змінюють поведінку, а не просто додають число до характеристики.
    /// УВАГА: значення серіалізуються як числа в ассетах апгрейдів — нові додавай лише в кінець.
    /// </summary>
    public enum PerkId
    {
        None = 0,

        /// <summary>Лук: додаткові стріли за постріл. Значення = кількість додаткових стріл.</summary>
        MultiShot = 1,

        /// <summary>Меч: ширший замах. Значення = додаткові градуси до кута атаки (максимум 360 разом).</summary>
        WideSwing = 2,

        /// <summary>Меч: лікування за замах, що влучив хоча б в одного ворога. Значення = HP за замах.</summary>
        Vampirism = 3,

        /// <summary>Ривок завдає урону ворогам на шляху. Значення = урон.</summary>
        DeadlyDash = 4,

        /// <summary>Більший радіус притягування сфер досвіду. Значення = частка до радіуса (0.5 = +50%).</summary>
        Magnet = 5,
    }
}
